#!/usr/bin/env node

/**
 * Docs build: validates content MDX docs and generates
 * - src/generated/component-index.ts (sidebar + catalog data)
 * - src/generated/demo-map.ts (slug -> lazy demo module)
 * - src/lib/component-categories.ts (canonical categories, from scripts/lib)
 */
import fs from "fs";
import path from "path";
import matter from "gray-matter";
import { componentDocSchema } from "./component-doc-schema.mjs";
import { categories } from "./lib/categories.mjs";
import {
  CONTENT_DIR,
  GENERATED_DIR,
  CATEGORIES_TS_PATH,
  getDemoNames,
  getDocFiles,
  readRegistry,
  registryNames,
} from "./lib/docs.mjs";

const COMPONENT_INDEX_PATH = path.join(GENERATED_DIR, "component-index.ts");
const DEMO_MAP_PATH = path.join(GENERATED_DIR, "demo-map.ts");

const registry = readRegistry();
const names = registryNames(registry);
const demoNames = getDemoNames();

const docs = getDocFiles(CONTENT_DIR)
  .map((filePath) => {
    const slug = path.basename(filePath, ".mdx");
    const { data } = matter(fs.readFileSync(filePath, "utf8"));
    return { slug, ...componentDocSchema.parse(data) };
  })
  .sort((a, b) => (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));

for (const name of names) {
  if (!docs.some((doc) => doc.slug === name)) {
    throw new Error(`Missing MDX documentation for registry component "${name}".`);
  }
}

const componentIndexOutput = `// Generated by scripts/build-docs.mjs. Do not edit manually.\n` +
  `import type { ComponentCategory } from "@/lib/component-categories";\n\n` +
  `export interface ComponentIndexItem {\n` +
  `  slug: string;\n  title: string;\n  description: string;\n  category: ComponentCategory;\n}\n\n` +
  `export const componentIndex: ComponentIndexItem[] = ${JSON.stringify(
    docs.map(({ slug, title, description, category }) => ({ slug, title, description, category })),
    null,
    2,
  )} as ComponentIndexItem[];\n`;

const demoEntries = demoNames
  .map((name) => `  "${name}": dynamic(() => import("@/demos/${name}")),`)
  .join("\n");

const demoMapOutput = `// Generated by scripts/build-docs.mjs. Do not edit manually.\n` +
  `import dynamic from "next/dynamic";\n\n` +
  `export const demos = {\n${demoEntries}\n} as const;\n\n` +
  `export type DemoName = keyof typeof demos;\n`;

const categoriesOutput = `// Generated by scripts/build-docs.mjs from scripts/lib/categories.mjs. Do not edit manually.\n` +
  `export const componentCategories = ${JSON.stringify(categories, null, 2)} as const;\n\n` +
  `export type ComponentCategory = (typeof componentCategories)[number]["id"];\n\n` +
  `export function getCategoryMetadata(category: ComponentCategory) {\n` +
  `  return componentCategories.find((item) => item.id === category)!;\n` +
  `}\n`;

const outputs = [
  { path: COMPONENT_INDEX_PATH, content: componentIndexOutput, label: "component index" },
  { path: DEMO_MAP_PATH, content: demoMapOutput, label: "demo map" },
  { path: CATEGORIES_TS_PATH, content: categoriesOutput, label: "categories" },
];

if (process.argv.includes("--check")) {
  for (const { path: outputPath, content, label } of outputs) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8") !== content) {
      throw new Error(
        `${label} is stale. Run bun docs:build and commit the result.`,
      );
    }
  }
  console.log(`✓ Validated ${docs.length} MDX documents, ${demoNames.length} demos`);
} else {
  for (const { path: outputPath, content, label } of outputs) {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, content);
    console.log(`✓ Generated ${label} (${path.relative(process.cwd(), outputPath)})`);
  }
}
